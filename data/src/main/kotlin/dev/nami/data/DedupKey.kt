package dev.nami.data

/** Единое правило дедупа треков по всей библиотеке: "название - альбом - артист, если всё
 * совпадает - дедуп" (Проблемы.md). Раньше каждое место, где трек попадает в библиотеку (импорт,
 * приём с другого устройства, зеркала сервера), сравнивало по-своему - где-то с допуском по
 * длительности, где-то вовсе без альбома. Здесь одна функция нормализации, чтобы дедуп по всей
 * библиотеке был одним и тем же правилом, а не набором похожих, но разных условий. */
object DedupKey {
    /** Регистронезависимое сравнение с обрезкой пробелов - "Song " и "song" не должны считаться
     * разными треками только из-за форматирования тега. */
    fun normalize(text: String?): String = text?.trim()?.lowercase() ?: ""

    /** true, если название+артист+альбом совпадают после нормализации. Артист и альбом должны
     * быть уже приведены к "основному" виду вызывающим кодом (см. MetadataResolver.primaryArtistName -
     * "Artist feat. X" и "Artist" не должны считаться разными исполнителями).
     *
     * Неизвестный альбом хотя бы с одной стороны совпадению НЕ мешает. Требование было
     * "треки всегда не дублировались", а строгое сравнение работало бы против него: локальный
     * файл часто импортируется без тега альбома, тогда как сервер тот же трек знает с альбомом,
     * и в библиотеке появлялась бы пара одинаковых записей. Альбом разводит треки только когда
     * он известен обеим сторонам и при этом разный. */
    fun matches(
        title: String,
        artistName: String?,
        albumName: String?,
        otherTitle: String,
        otherArtistName: String?,
        otherAlbumName: String?,
    ): Boolean {
        if (normalize(title) != normalize(otherTitle)) return false
        if (normalize(artistName) != normalize(otherArtistName)) return false
        val album = normalize(albumName)
        val otherAlbum = normalize(otherAlbumName)
        return album.isEmpty() || otherAlbum.isEmpty() || album == otherAlbum
    }
}
