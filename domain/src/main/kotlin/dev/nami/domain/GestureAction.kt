package dev.nami.domain

/** Группа E "настраиваемые жесты" - честно узкий скоуп: один жест (двойной тап по обложке на
 * Now Playing), который раньше вообще ничего не делал. Остальные жесты в приложении (свайп
 * мини-плеера, вертикальный свайп для закрытия Now Playing) уже жёстко закреплены за своим
 * действием - перепривязывать их отдельная, более рискованная задача. */
enum class GestureAction {
    NONE,
    TOGGLE_LIKE,
    SKIP_NEXT,
    PREV_TRACK,
    PLAY_PAUSE,
    SHOW_LYRICS,
    SHUFFLE,
}

