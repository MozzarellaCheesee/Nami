package dev.nami.domain

/**
 * П.md §17 "Now Playing - конструктор макета", часть "порядок блоков". Это ровно те вертикальные
 * секции, что идут НИЖЕ обложки и не участвуют в её жестах: сам пейджер обложки в списке
 * отсутствует намеренно и всегда остаётся сверху - вокруг него завязана вся drag/fling/
 * автопродвижение логика, и двигать его местами - гарантированно ломать стабильное.
 *
 * Пресеты макета (Классический / Крупная обложка / ...) из плана не сделаны: они складываются из
 * этого порядка и уже существующих переключателей, отдельный список пресетов поверх них - лишний
 * слой, пока нет запроса.
 */
enum class NowPlayingBlock {
    /** Название трека, лайк, исполнитель. */
    TITLE_ARTIST,

    /** Скраббер (волна или линия) плюс строка времени под ним. */
    PROGRESS,

    /** Ряд транспорта: перемешать / назад / играть / вперёд / зациклить. */
    TRANSPORT,

    /** Бейдж формата и битрейта. */
    TECH_INFO,

    /** Нижний ряд: Очередь, ночной режим, Текст. */
    PILLS,
}

/** Порядок по умолчанию - тот, что был захардкожен в NowPlayingScreen до появления настройки. */
val DEFAULT_NOW_PLAYING_BLOCKS = listOf(
    NowPlayingBlock.TITLE_ARTIST,
    NowPlayingBlock.PROGRESS,
    NowPlayingBlock.TRANSPORT,
    NowPlayingBlock.TECH_INFO,
    NowPlayingBlock.PILLS,
)
